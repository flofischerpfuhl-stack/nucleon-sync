const pl = (x: number, one: string, many: string) => `${n(x)} ${x === 1 ? one : many}`;

/** sizes and remaining times inside service texts (binary units like the rest of the app) */
const bytes = (b: number): string => {
  const units = ['B', 'KB', 'MB', 'GB', 'TB', 'PB'];
  let v = b;
  let i = 0;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${n(i === 0 || v >= 9.95 ? Math.round(v) : Math.round(v * 10) / 10)} ${units[i]}`;
};
const gib = (b: number): string => `${n(Math.round((b / 1024 ** 3) * 10) / 10)} GB`;
const secs = (sec: number): string => {
  if (sec < 90) return `${n(Math.max(1, Math.round(sec)))} s`;
  if (sec < 5400) return `${n(Math.round(sec / 60))} min`;
  const h = Math.floor(sec / 3600);
  return h >= 48 ? `${n(Math.round(h / 24))} Tage` : `${n(h)} h ${n(Math.round((sec % 3600) / 60))} min`;
};

